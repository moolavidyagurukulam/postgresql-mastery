-- === IDENTITY — The Modern Standard (PG 10+, preferred in PG 16) ===

-- GENERATED ALWAYS: database controls the id (recommended)
CREATE TABLE users (
    id   INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

INSERT INTO users (name) VALUES ('Ravi'), ('Priya'), ('Arjun');
SELECT * FROM users;  -- ids: 1, 2, 3

-- Manual insert is BLOCKED:
-- INSERT INTO users (id, name) VALUES (10, 'Meera');
-- ERROR: cannot insert a non-DEFAULT value into column "id"
-- HINT: Use OVERRIDING SYSTEM VALUE to override.

-- Override when needed (rare):
INSERT INTO users (id, name) OVERRIDING SYSTEM VALUE VALUES (10, 'Meera');

-- GENERATED BY DEFAULT: allows manual ids (like SERIAL)
CREATE TABLE products (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

INSERT INTO products (name) VALUES ('Laptop');       -- id=1 (auto)
INSERT INTO products (id, name) VALUES (100, 'Mouse');  -- id=100 (manual, OK)
INSERT INTO products (name) VALUES ('Keyboard');     -- id=2 (auto continues)

-- Custom sequence options:
CREATE TABLE invoices (
    id     INT GENERATED ALWAYS AS IDENTITY
             (START WITH 1000 INCREMENT BY 1) PRIMARY KEY,
    amount NUMERIC(10,2) NOT NULL
);

INSERT INTO invoices (amount) VALUES (299.99), (149.50), (599.00);
SELECT * FROM invoices;  -- ids: 1000, 1001, 1002

-- === SERIAL vs IDENTITY ===

-- SERIAL: PostgreSQL-specific, always allows manual ids,
--         separate sequence object, can break on pg_dump
-- IDENTITY: SQL standard, GENERATED ALWAYS blocks manual ids,
--           built-in management, clean dump/restore
-- RECOMMENDATION: Use IDENTITY for new tables in PG 16

-- === SEQUENCE FUNCTIONS ===

-- Create a standalone sequence
CREATE SEQUENCE order_num_seq
  START WITH 1000
  INCREMENT BY 1
  MINVALUE 1000
  MAXVALUE 999999
  NO CYCLE;

-- nextval: get NEXT value (advances the sequence)
SELECT nextval('order_num_seq');  -- 1000
SELECT nextval('order_num_seq');  -- 1001
SELECT nextval('order_num_seq');  -- 1002

-- currval: last nextval value IN THIS SESSION
SELECT currval('order_num_seq');  -- 1002

-- ERROR: currval before nextval in a new session
-- SELECT currval('order_num_seq');
-- ERROR: currval of sequence "order_num_seq" is not yet
--        defined in this session
-- Fix: call nextval first

-- setval: manually set the sequence
SELECT setval('order_num_seq', 5000);
SELECT nextval('order_num_seq');  -- 5001

-- setval with false: next nextval returns this exact value
SELECT setval('order_num_seq', 5000, false);
SELECT nextval('order_num_seq');  -- 5000

-- === SEQUENCE GAPS ARE NORMAL ===

-- Gaps happen because:
-- 1. Rolled-back transactions (nextval never rolls back)
-- 2. Failed INSERTs (after nextval was called)
-- 3. Cached sequence values (CACHE option)
-- 4. Deleted rows

-- Example:
BEGIN;
  INSERT INTO users (name) VALUES ('Test');  -- gets id 11
ROLLBACK;
-- id 11 is GONE. Next insert gets id 12. That's normal.
INSERT INTO users (name) VALUES ('After Rollback');
SELECT * FROM users ORDER BY id;
-- You'll see: ...10, 12 (11 is skipped)

-- Sequences guarantee UNIQUE, not CONTIGUOUS
-- Don't try to make them gapless!

-- === RESYNC SEQUENCE AFTER DATA IMPORT ===

-- After importing data, sequence may be out of sync
-- Fix: set sequence to max id in the table

-- For SERIAL:
SELECT setval('orders_serial_id_seq', (SELECT MAX(id) FROM orders_serial));

-- For IDENTITY: use ALTER
-- ALTER TABLE users ALTER COLUMN id RESTART WITH <next_value>;

-- Find out-of-sync sequences:
SELECT c.relname AS table_name,
       a.attname AS column_name,
       pg_get_serial_sequence(c.relname, a.attname) AS seq_name
FROM pg_class c
JOIN pg_attribute a ON a.attrelid = c.oid
WHERE pg_get_serial_sequence(c.relname, a.attname) IS NOT NULL;

-- === TEMPORARY TABLES ===

-- Session-scoped: exists only for current session
CREATE TEMP TABLE cart_items (
    id       SERIAL PRIMARY KEY,
    product  VARCHAR(100),
    qty      INT DEFAULT 1,
    added_at TIMESTAMPTZ DEFAULT NOW()
);

INSERT INTO cart_items (product, qty) VALUES
('Laptop', 1), ('Mouse', 2), ('Keyboard', 1);

SELECT * FROM cart_items;

-- Invisible to other sessions!
-- Auto-dropped when session ends!

-- ON COMMIT options (inside transactions):
-- PRESERVE ROWS  → keep data (default)
-- DELETE ROWS    → empty table after each COMMIT
-- DROP           → drop table after COMMIT

CREATE TEMP TABLE txn_scratch (
    data TEXT
) ON COMMIT DELETE ROWS;

BEGIN;
  INSERT INTO txn_scratch VALUES ('temp data');
  SELECT * FROM txn_scratch;  -- 1 row
COMMIT;
SELECT * FROM txn_scratch;    -- 0 rows (deleted on commit!)

-- WARNING: temp tables shadow real tables with same name!
-- CREATE TEMP TABLE users (...);
-- Now SELECT * FROM users hits the TEMP table, not the real one!

-- === UNLOGGED TABLES ===

-- No WAL (Write-Ahead Log) = faster writes
-- But data LOST on crash (table truncated automatically)

CREATE UNLOGGED TABLE session_cache (
    id        SERIAL PRIMARY KEY,
    user_id   INT,
    data      JSONB,
    cached_at TIMESTAMPTZ DEFAULT NOW()
);

INSERT INTO session_cache (user_id, data) VALUES
(1, '{"page": "dashboard", "filters": ["active"]}'),
(2, '{"page": "reports", "filters": ["2026"]}');

SELECT * FROM session_cache;  -- Works like a normal table

-- Performance: 2-3x faster writes than regular tables
-- Risk: crash → data gone, table structure survives

-- Good for: caches, intermediate computation, scratch data
-- BAD for: orders, users, financial data — NEVER unlogged!

-- Convert unlogged → logged (and vice versa):
ALTER TABLE session_cache SET LOGGED;    -- now crash-safe
ALTER TABLE session_cache SET UNLOGGED;  -- fast again, risky

-- === REGULAR vs TEMPORARY vs UNLOGGED ===

-- Regular:    visible to all, WAL-logged, survives crash
-- Temporary:  session-only, auto-dropped, no WAL
-- Unlogged:   visible to all, no WAL, data lost on crash

