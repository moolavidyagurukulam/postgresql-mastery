-- === SERIAL — What It Actually Creates ===

-- SERIAL is a shortcut, not a real data type
CREATE TABLE orders_serial (
    id      SERIAL PRIMARY KEY,
    product VARCHAR(100)
);

-- What PostgreSQL ACTUALLY creates:
-- 1. CREATE SEQUENCE orders_serial_id_seq;
-- 2. Column: id INT NOT NULL DEFAULT nextval('orders_serial_id_seq')
-- 3. ALTER SEQUENCE orders_serial_id_seq OWNED BY orders_serial.id

-- Variants:
-- SERIAL      = INTEGER (4 bytes, max 2.1 billion)
-- BIGSERIAL   = BIGINT  (8 bytes, max 9.2 quintillion)
-- SMALLSERIAL = SMALLINT (2 bytes, max 32,767)

INSERT INTO orders_serial (product) VALUES ('Laptop'), ('Mouse'), ('Keyboard');
SELECT * FROM orders_serial;  -- ids: 1, 2, 3

